package dev.cf;

import java.io.IOException;
import java.nio.ByteBuffer;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Comparator;

/** Pure-Java regression, no server or Minecraft world needed. */
public final class CFMapWindowSelfTest {
    private static int checks;
    private static void ok(boolean value, String why) {
        checks++;
        if (!value) throw new AssertionError(why);
    }

    public static void main(String[] args) throws Exception {
        ok(CFMapWindow.RADIUS_CHUNKS == 50, "exact 50 chunk radius");
        ok(CFMapWindow.MAX_CHUNKS == 10201, "inclusive 101 by 101 window");
        for (int x = -51; x <= 51; x++) {
            for (int z = -51; z <= 51; z++) {
                boolean allowed = x >= -50 && x <= 50 && z >= -50 && z <= 50;
                ok(CFMapWindow.includesChunk(x, z) == allowed, "chunk edge " + x + "," + z);
            }
        }
        for (int rx = -3; rx <= 2; rx++) {
            for (int rz = -3; rz <= 2; rz++) {
                boolean expected = rx >= -2 && rx <= 1 && rz >= -2 && rz <= 1;
                ok(CFMapWindow.includesRegion(rx, rz) == expected, "region edge");
            }
        }
        ok(!CFMapWindow.includesRegion(Integer.MAX_VALUE, Integer.MIN_VALUE), "no overflow");

        Path root = Files.createTempDirectory("cf-map-window-");
        try {
            Path dir = root.resolve("dimensions/minecraft/overworld/region");
            Files.createDirectories(dir);
            for (int rx = -2; rx <= 1; rx++) {
                for (int rz = -2; rz <= 1; rz++) {
                    ByteBuffer header = ByteBuffer.allocate(4096);
                    for (int i = 0; i < 1024; i++) {
                        // Mark every slot (including out-of-window slots in
                        // boundary regions) to test accurate chunk clipping.
                        header.putInt(i * 4, 0x00000201);
                    }
                    Files.write(dir.resolve("r." + rx + "." + rz + ".mca"), header.array());
                }
            }
            // An out-of-range file is deliberately NOT a valid region header:
            // attempting to open it must fail, so discovery must skip it.
            Files.write(dir.resolve("r.2.0.mca"), new byte[] {1});
            Files.write(dir.resolve("r.-3.-3.mca"), new byte[] {1});
            ok(CFMapWindow.relevantRegions(root).size() == 16, "16 intersecting regions");
            var discovered = CFMapWindow.discoverAnvil(root);
            ok(discovered.size() == 10201, "all 10,201 in-window chunks accepted");
            ok(discovered.contains(key(-50, -50)), "negative boundary included");
            ok(discovered.contains(key(50, 50)), "positive boundary included");
            ok(discovered.contains(key(0, 0)), "origin included");
            ok(!discovered.contains(key(51, 0)), "outside east excluded");
            ok(!discovered.contains(key(-51, 0)), "outside west excluded");
            ok(!discovered.contains(key(0, 51)), "outside south excluded");
            ok(!discovered.contains(key(0, -51)), "outside north excluded");
            Files.delete(dir.resolve("r.0.0.mca"));
            ok(CFMapWindow.discoverAnvil(root).size() == 10201 - 1024,
                    "only existing chunks loaded; no blank chunks generated by scanning");
        } finally {
            try (var walk = Files.walk(root)) {
                for (var file : walk.sorted(Comparator.reverseOrder()).toList())
                    Files.deleteIfExists(file);
            }
        }
        System.out.println("[КФ ОКНО КАРТЫ] ПРОЙДЕНО " + checks
                + " проверок: радиус 50, 10 201 чанков, Anvil, границы и отсутствие записи в мир.");
    }

    private static long key(int x, int z) {
        return ((long) x << 32) ^ (z & 0xffffffffL);
    }
}
